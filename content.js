let drillDialog = null;
function openDrill(key) {
  const [subj, topic] = key.split(':');
  const idx = EXAM_TOPICS[subj].topics.indexOf(topic);
  if (!drillDialog) {
    document.body.insertAdjacentHTML('beforeend',
      '<dialog class="dialog drill-dialog" id="drillDialog"><div class="dialog-body" id="drillBody"></div></dialog>');
    drillDialog = document.querySelector('#drillDialog');
    drillDialog.addEventListener('click', e => {
      if (e.target.closest('[data-close]') || e.target === drillDialog) drillDialog.close();
    });
  }
  const body = document.querySelector('#drillBody');
  body.innerHTML = `
    <button type="button" class="dialog-close" data-close aria-label="Закрыть">
      <svg class="icon" aria-hidden="true"><use href="#i-x"/></svg></button>
    <h2>${topic}</h2>
    <p class="muted">${EXAM_TOPICS[subj].name} · ${EXAM_TOPICS[subj].exam}</p>
    <div class="drill-note"><b>Конспект.</b> ${(NOTES[subj] && NOTES[subj][idx]) || 'Открой раздел теории и повтори тему перед практикой.'}</div>
    <div class="drill-task" id="drillTask"></div>
    <div class="drill-actions">
      <button type="button" class="btn btn-primary" id="drillCheck">Проверить</button>
      <button type="button" class="btn" id="drillNew">Другая задача</button>
      <button type="button" class="btn" data-close>Закрыть</button>
    </div>
    <p class="drill-msg" id="drillMsg" role="status"></p>`;
  let task = null;
  const shuffle = a => a.map(v => [Math.random(), v]).sort((x, y) => x[0] - y[0]).map(p => p[1]);
  const make = () => {
    const msg = document.querySelector('#drillMsg');
    msg.textContent = ''; msg.className = 'drill-msg';
    const g = GEN[subj] && GEN[subj][idx];
    if (g) {
      task = Object.assign({ type: 'num' }, g());
      document.querySelector('#drillTask').innerHTML = `<p class="drill-q">${task.q}</p>
        <input type="text" id="drillAns" inputmode="decimal" placeholder="Твой ответ" autocomplete="off">`;
    } else {
      const qz = QUIZ[subj] && QUIZ[subj][idx];
      if (!qz) { task = null; document.querySelector('#drillTask').innerHTML = '<p class="muted">Для этой темы задачи скоро появятся.</p>'; return; }
      const opts = shuffle(qz[1]);
      task = { type: 'quiz', q: qz[0], opts, correct: opts.indexOf(qz[2]) };
      document.querySelector('#drillTask').innerHTML = `<p class="drill-q">${task.q}</p>
        <div class="drill-opts">${opts.map((o, i) =>
          `<label class="drill-opt"><input type="radio" name="drillOpt" value="${i}"><span>${o}</span></label>`).join('')}</div>`;
    }
  };
  document.querySelector('#drillNew').addEventListener('click', make);
  document.querySelector('#drillCheck').addEventListener('click', () => {
    if (!task) return;
    const msg = document.querySelector('#drillMsg');
    let ok = false;
    if (task.type === 'num') {
      const raw = (document.querySelector('#drillAns').value || '').replace(',', '.').trim();
      const val = Number(raw);
      ok = raw !== '' && Math.abs(val - task.a) < 0.011;
    } else {
      const sel = body.querySelector('input[name=drillOpt]:checked');
      ok = sel && Number(sel.value) === task.correct;
    }
    msg.textContent = ok ? 'Верно! Так держать.' : `Пока нет. Правильный ответ: ${task.type === 'num' ? task.a : task.opts[task.correct]}.`;
    msg.className = 'drill-msg ' + (ok ? 'ok' : 'bad');
  });
  make();
  drillDialog.showModal();
}
window.openDrill = openDrill;
